package app.nursemate.wear.ui

/**
 * 워치가 사용자에게 알려야 할 사정.
 *
 * 둘 다 **워치가 스스로 해결할 수 없는 일**이라 안내로 끝난다 — 폰을 꺼내야 풀린다.
 * spec §워치는 상태를 워치가 직접 바꾸지 않는다고 했으므로 여기서 손쓸 여지가 없다.
 */
enum class WearNotice(val title: String, val body: String) {

    /**
     * 폰에서 아직 시작 준비가 안 됐다 — 알람 권한이 없거나 울림 방식을 안 골랐다.
     *
     * 스냅샷의 `alarmAuthorized` 가 그 둘을 합쳐 알려 준다. 이대로 보내면 폰이 조용히
     * 거절해 **눌러도 아무 일이 없는 것처럼** 보인다.
     *
     * 둘을 나눠 안내하지 않는다 — 사용자가 할 일은 어느 쪽이든 "폰에서 한 번 시작해
     * 관문을 지나는 것" 하나다.
     */
    PHONE_PERMISSION(
        title = "폰에서 먼저 준비해주세요",
        body = "폰의 널스메이트에서 타이머를 한 번 시작해 알람 설정을 마쳐주세요."
    ),

    /** 명령이 폰에 닿지 않았다 — 폰이 꺼져 있거나 연결이 끊겼다. */
    UNDELIVERED(
        title = "폰에 전달하지 못했어요",
        body = "폰이 켜져 있고 워치와 연결됐는지 확인해주세요."
    )
}
